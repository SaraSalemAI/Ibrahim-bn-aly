export function makeT(lang: Language) {
  const dict = lang === "ar" ? ar : en;
  const idx = lang === "ar" ? 1 : 0;
  const t = (key: string, params?: Record<string, string | number>) => {
    let s = dict[key] ?? en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
  return {
    t,
    category: (c: Category) => CATEGORY_LABELS[c][idx],
    line: (k: string) => LINE_LABELS[k]?.[idx] ?? k,
    issue: (i: Issue, fmt: (n: number) => string) => {
      const params: Record<string, string | number> = { ...i.params };
      if (typeof params.difference === "number") params.difference = fmt(params.difference);
      if (typeof params.period === "string") params.period = t(`period_${params.period}`);
      return t(`issue_${i.code}`, params);
    },
  };
}
